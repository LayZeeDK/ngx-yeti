// PROTOTYPE (ticket 18): turns results/<mode>.json into results/report.md.
// A cell shows one value when Chromium, Firefox, and WebKit agree, else c/f/w.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const MODES = ['none', 'noreplay', 'replay', 'plain', 'explicit', 'zone', 'i18n-off', 'i18n-on'];
const B = ['chromium', 'firefox', 'webkit'];
const R = Object.fromEntries(MODES.filter((m) => existsSync(`results/${m}.json`)).map((m) => [m, JSON.parse(readFileSync(`results/${m}.json`, 'utf8'))]));
const modes = Object.keys(R);
const fmt = (v) => (v === undefined ? '-' : typeof v === 'string' ? v : JSON.stringify(v)).replaceAll('|', '/');
const cell = (m, fn) => {
  const vals = B.map((b) => {
    try {
      return fmt(fn(R[m].browsers[b], R[m]));
    } catch {
      return 'n/a';
    }
  });

  return vals.every((v) => v === vals[0]) ? vals[0] : `c ${vals[0]}; f ${vals[1]}; w ${vals[2]}`;
};
const table = (title, rows) => {
  let s = `\n### ${title}\n\n| Measure | ${modes.join(' | ')} |\n| --- | ${modes.map(() => '---').join(' | ')} |\n`;
  for (const [label, fn] of rows) {
    s += `| ${label} | ${modes.map((m) => cell(m, fn)).join(' | ')} |\n`;
  }

  return s;
};

let out = '# Results (generated by tools/report.mjs)\n\n';
const first = R[modes[0]].browsers;
out += `Browsers: ${B.map((b) => `${b} ${first[b].version}`).join(', ')} (Playwright 1.63.0).\n`;

out += table('Server HTML', [
  ['home: `ngh` annotations', (b, r) => r.server.home.ngh],
  ['home: `ngskiphydration`', (b, r) => r.server.home.skipHydration],
  ['home: replayed event types', (b, r) => r.server.home.bootstrap?.match(/\[.*\]/)?.[0] ?? 'none'],
  ['pre: `ng-server-context`', (b, r) => r.server.pre.serverContext + (r.prerenderFile ? ' (file)' : ' (no file)')],
  ['i18n: `ngskiphydration`', (b, r) => r.server.i18n.skipHydration],
  ['i18n: card title', (b, r) => r.server.i18n.cardTitle],
  ['defer: blocks rendered with content', (b, r) => r.server.defer.blocksWithContent.join(' ') || 'none'],
  ['guard: badge `<style>` in HTML', (b, r) => r.server.guard.badgeStyle],
]);

out += table('JavaScript off (home)', [
  ['card and grid laid out', (b) => b.jsOff.cardVisible && b.jsOff.layoutBoxes.every((x) => x && x.width > 0) && b.jsOff.layoutBoxes[1].y === b.jsOff.layoutBoxes[0].y],
  ['dialog hidden, opens by invoker, Escape closes', (b) => [!b.jsOff.dialogVisibleBefore, b.jsOff.dialogVisibleAfterClick, !b.jsOff.dialogVisibleAfterEscape].every(Boolean)],
  ['dropdown hidden, opens by popovertarget', (b) => !b.jsOff.dropdownVisibleBefore && b.jsOff.dropdownVisibleAfterClick],
  ['accordion opens', (b) => b.jsOff.accOpenAfterClick],
  ['tab panels visible', (b) => b.jsOff.tabPanelsVisible],
  ['carousel dot URL', (b) => b.jsOff.urlAfterDot],
]);

out += table('Hydration after a normal load', [
  ['home: elements removed', (b) => b.hydrateHome.removed],
  ['home: attribute values changed', (b) => [...new Set(b.hydrateHome.changed.map((c) => `${c.k}:${c.old}->${c.now}`))].join(', ') || 'none'],
  ['home: tabs.js state kept', (b) => b.hydrateHome.tabState.selected.join('/') + ` hidden=${b.hydrateHome.tabState.hiddenPanels}`],
  ['home: tabs2 (static aria-selected) after load', (b) => b.hydrateHome.tabState.tabs2Selected.join('/')],
  ['home: `.enter[data-once]` still has data-once', (b) => b.hydrateHome.tabState.enterOnceDataOnce],
  ['home: `.enter` animation starts (server element)', (b) => b.hydrateHome.enterSsrAnimations],
  ['home: console errors', (b) => b.hydrateHome.errors.length],
  ['pre: elements removed', (b) => b.hydratePre.removed],
  ['i18n: elements removed', (b) => b.hydrateI18n.removed],
  ['i18n: tabs.js state after load', (b) => b.hydrateI18n.tabState.selected.join('/') + ` hidden=${b.hydrateI18n.tabState.hiddenPanels}`],
  ['i18n: card title / body', (b) => `${b.hydrateI18n.cardTitle} / ${b.hydrateI18n.cardBody}`],
]);

const P = (b) => b.beforeHydrationAll;
out += table('Before hydration (main.js held back), then after', [
  ['pre: dialog opens and closes natively', (b) => P(b).pre.dialogOpened && P(b).pre.dialogClosedByEscape],
  ['pre: popover opens natively', (b) => P(b).pre.popoverOpened],
  ['pre: details open natively (plain/bound)', (b) => `${P(b).pre.accPlainOpen}/${P(b).pre.accBoundOpen}`],
  ['pre: tabs.js selects tab B', (b) => P(b).pre.tabBSelected],
  ['pre: carousel dot: hash, history delta', (b) => `${P(b).pre.dotHash || '(none)'}, ${P(b).pre.dotHistoryDelta}`],
  ['pre: closed the static-open details', (b) => !P(b).pre.accStaticOpen],
  ['post: elements removed', (b) => P(b).post.removed],
  ['post: counter after 2 early clicks', (b) => P(b).post.counterText],
  ['post: input value / Angular mirror', (b) => `${P(b).post.inputValue}/${P(b).post.mirror}`],
  ['post: replayed handler runs (click, input, details toggle, popover toggle)', (b) => [P(b).post.t.counterClick ?? 0, P(b).post.t.input ?? 0, P(b).post.t.detailsToggle ?? 0, P(b).post.t.popoverToggle ?? 0].join('/')],
  ['post: plain details still open', (b) => P(b).post.accPlainOpen],
  ['post: `[open]`-bound details still open', (b) => P(b).post.accBoundOpen],
  ['post: static-open details (user closed it)', (b) => (P(b).post.accStaticOpen ? 'reopened' : 'stays closed')],
  ['post: tab B still selected (tabs.js)', (b) => `${P(b).post.tabBSelected} hidden=${P(b).post.hiddenPanels}`],
  ['post: tabs2 aria-selected (user picked 2nd)', (b) => P(b).post.tabs2Selected.join('/') + ` hidden=${P(b).post.tabs2HiddenPanels}`],
  ['post: popover left open is still open', (b) => P(b).post.popoverOpen],
  ['post: `.enter[data-once]` has data-once', (b) => P(b).post.enterOnceDataOnce],
  ['dialog left open survives hydration', (b) => b.beforeHydrationDialog.post.dialogOpen],
  ['`(close)` runs for the later Escape', (b) => b.beforeHydrationDialog.post.closeHandlerRuns],
  ['early `dialog` close replayed to `(close)`', (b) => P(b).post.t.dialogClose ?? 0],
  ['i18n page: early click replayed', (b) => b.i18nBeforeHydration.counterRuns],
]);

const names = ['d-immediate', 'd-idle', 'd-timer', 'd-when', 'd-interaction', 'd-hover', 'd-viewport', 'h-immediate', 'h-idle', 'h-timer', 'h-when', 'h-interaction', 'h-hover', 'h-viewport', 'h-never'];
const st = (x) => (!x.content ? 'empty' : x.created ? 'live' : 'dehydrated') + (x.tabsInit === null ? '' : x.tabsInit ? ',tabs' : ',no-tabs');
out += table('`@defer` blocks: state before -> after its trigger (live = created/hydrated; tabs = tabs.js initialised)', [
  ...names.map((n) => [n, (b) => `${st(b.defer.before[n])} -> ${st(b.defer.after[n])}` + (b.defer.after[n].clicks ? ` clicks=${b.defer.after[n].clicks}` : '')]),
  ['h-never: native dialog opens', (b) => b.defer.neverDialogOpened],
  ['d-idle (client-rendered): native dialog opens', (b) => b.defer.clientDialogOpened],
  ['action errors', (b) => b.defer.actionErrors.join('; ') || 'none'],
]);

const A = (b) => b.anim;
out += table('`animate.enter`, `animate.leave`, and Yeti motion', [
  ['dialog inserted open: Yeti @starting-style transition', (b) => A(b).dialogEnter.anims.join('+')],
  ['dialog `animate.leave` class: transitions, removed at ms', (b) => `${A(b).dialogLeave.anims.join('+')}, ${A(b).dialogLeave.removedAtMs}`],
  ['`animate.enter="enter"`: animation, class after', (b) => `${A(b).enterClassEnter.anims.join('+')}, ${A(b).enterClassEnter.last.cls}`],
  ['static `.enter` inserted by @if', (b) => A(b).enterStaticEnter.anims.join('+') || 'none'],
  ['`.enter[data-once]` inserted by @if: animation, opacity, data-once', (b) => `${A(b).enterOnceEnter.anims.join('+') || 'none'}, ${A(b).enterOnceEnter.last.opacity}, ${A(b).enterOnceEnter.last.dataOnce}`],
  ['server `.enter[data-once]` after load: data-once, animations', (b) => `${A(b).onceSsr.dataOnce}, ${A(b).onceSsr.anims}`],
  ['alert `animate.leave` (300 ms keyframes): removed at ms', (b) => A(b).alert2Leave.removedAtMs],
  ['alert.js removes an @if-owned alert: removed at ms', (b) => A(b).alertJsClose.removedAtMs],
  ['then Angular hides / shows it: count, errors', (b) => `${A(b).alertAfterAngularHide}/${A(b).alertAfterAngularShow}, ${A(b).alertErrors.length}`],
]);

const G = (b) => b.guard;
out += table('Leave-animation style guard (badge.css through `styleUrl`)', [
  ['G0 no leave animation: badge `<style>` after hide', (b) => G(b).G0_noLeaveAnywhere.stylesAfterHide],
  ['G1 permanent class-form `animate.leave`', (b) => G(b).G1_permanentClassLeave.stylesAfterHide],
  ['G2 permanent function-form `(animate.leave)`', (b) => G(b).G2_permanentFnLeave.stylesAfterHide],
  ['G3 badge removed with a leaving sibling: during / after', (b) => `${G(b).G3_badgeWithLeavingSibling.stylesDuringLeave}/${G(b).G3_badgeWithLeavingSibling.stylesAfterLeave}`],
  ['`hydrate never` badge padding: at load -> after eager badge hides', (b) => `${G(b).G0_noLeaveAnywhere.neverAtLoad?.paddingInline} -> ${G(b).G0_noLeaveAnywhere.neverAfterHide?.paddingInline}`],
]);

out += table('Change detection (yeti:* events)', [
  ['`(document:yeti:select)` host listener: runs / view', (b) => `${b.hydrateHome.afterTabClick.hostListenerRuns}/${b.hydrateHome.afterTabClick.hostListenerView}`],
  ['`yeti:slide` with only a plain field: runs / view', (b) => `${b.hydrateHome.afterDotClick.plainSlideRuns}/${b.hydrateHome.afterDotClick.plainSlidesView}`],
  ['`yeti:slide` into an Eager component plain field (root is Eager): runs / view', (b) => `${b.hydrateHome.afterDotClick.defaultCdRuns}/${b.hydrateHome.afterDotClick.defaultCdView}`],
  ['zone.js loaded', (b) => b.hydrateHome.afterDotClick.zoneLoaded],
  ['counter click after hydration', (b) => b.hydrateHome.counterAfterClick],
]);

const failures = [];
for (const m of modes) {
  for (const b of B) {
    for (const [k, v] of Object.entries(R[m].browsers[b])) {
      if (v && typeof v === 'object' && 'failed' in v) {
        failures.push(`${m} ${b} ${k}: ${v.failed}`);
      }
    }
  }
}
out += `\n### Steps that failed\n\n${failures.length ? failures.map((f) => '- ' + f).join('\n') : 'None.'}\n`;
writeFileSync('results/report.md', out);
console.log(out);
