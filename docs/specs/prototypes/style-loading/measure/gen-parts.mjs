// Generates projects/yeti-lib/src/lib/parts.ts from Yeti's own dist/css/yeti.css import order
// at the pin. In the package this would run at package build; the rank is the position of the
// part's file in that order, which fixes tie order inside a layer (ticket 23, section 4.4).
import fs from 'node:fs';

const yetiCss = fs.readFileSync('D:/tmp/ngx-yeti-13/app/node_modules/yeti-css/dist/css/yeti.css', 'utf8');
const parts = [];
for (const m of yetiCss.matchAll(/@import "((layouts|recipes|components|utilities)\/([\w-]+)\/\3\.css)";/g)) {
  parts.push({ name: m[3], path: m[1] });
}
if (parts.length !== 49) throw new Error(`expected 49 parts, found ${parts.length}`);
const lines = parts.map((p, i) => `  ${JSON.stringify(p.name)}: { path: ${JSON.stringify(p.path)}, rank: ${i} },`);
fs.writeFileSync(
  'D:/tmp/ngx-yeti-13/app/projects/yeti-lib/src/lib/parts.ts',
  `// Generated by measure/gen-parts.mjs from yeti-css/css/yeti.css at the pin. Do not edit.\n` +
    `export const YETI_COMMIT = 'f52d1e8b9';\n` +
    `export const YETI_PARTS = {\n${lines.join('\n')}\n} as const;\n` +
    `export type YetiPartName = keyof typeof YETI_PARTS;\n`,
);
console.log(`wrote ${parts.length} parts`);
